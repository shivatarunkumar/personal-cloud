// ---------------------------------------------------------------- file-type glyphs
// Solid, coloured glyphs (like OneDrive) so a folder reads as a folder at a glance.

export function FolderGlyph({ size = 24 }: { size?: number }) {
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden className="shrink-0">
      <path d="M2.5 6.5A2 2 0 0 1 4.5 4.5h4.3l2 2h8.7a2 2 0 0 1 2 2V18a2 2 0 0 1-2 2h-15a2 2 0 0 1-2-2V6.5Z" fill="var(--folder)" />
      <path d="M2.5 9h19v9a2 2 0 0 1-2 2h-15a2 2 0 0 1-2-2V9Z" fill="var(--folder)" opacity="0.8" />
    </svg>
  );
}

const KIND_LABEL: Record<Kind, string> = {
  image: "IMG",
  video: "VID",
  audio: "AUD",
  pdf: "PDF",
  text: "TXT",
  archive: "ZIP",
  document: "DOC",
  other: "",
};

export function FileGlyph({ kind, size = 24 }: { kind: Kind; size?: number }) {
  const color = `var(--k-${kind})`;
  return (
    <svg width={size} height={size} viewBox="0 0 24 24" aria-hidden className="shrink-0">
      <path d="M6 2.5h8l5 5V20a1.5 1.5 0 0 1-1.5 1.5h-11A1.5 1.5 0 0 1 5 20V4a1.5 1.5 0 0 1 1-1.5Z" fill={color} opacity="0.16" />
      <path d="M6.5 2.5H14l5 5v12.5a1.5 1.5 0 0 1-1.5 1.5h-11A1.5 1.5 0 0 1 5 20V4a1.5 1.5 0 0 1 1.5-1.5Z" stroke={color} strokeWidth="1.3" fill="none" />
      <path d="M14 2.5V7a.5.5 0 0 0 .5.5H19" stroke={color} strokeWidth="1.3" fill="none" />
      {kind === "image" && <path d="m7.5 18 3-3.5 2 2 1.5-1.5 2.5 3H7.5Z" fill={color} />}
      {kind === "video" && <path d="M10 12.5v5l4.2-2.5-4.2-2.5Z" fill={color} />}
      {kind === "audio" && <path d="M11 18.2a1.3 1.3 0 1 1-1.3-1.3c.3 0 .6.1.8.2V11.5l4.5-1v5.7a1.3 1.3 0 1 1-1-1.3V12l-3 .6v5.6Z" fill={color} />}
      {KIND_LABEL[kind] && kind !== "image" && kind !== "video" && kind !== "audio" && (
        <text x="12" y="17.6" textAnchor="middle" fontSize="5.2" fontWeight="700" fill={color} fontFamily="system-ui, sans-serif">
          {KIND_LABEL[kind]}
        </text>
      )}
    </svg>
  );
}
